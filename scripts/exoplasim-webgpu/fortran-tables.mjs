import fs from "node:fs/promises"
import path from "node:path"

// Converts constant tables in ExoPlaSim's Fortran into TypeScript modules,
// value for value: specblock.f90's spectra (solarini) and radmod.f90's
// Berger (1978) orbital series (orb_params).
// node scripts/exoplasim-webgpu/fortran-tables.mjs [<plasim/src directory>]
const sourceRoot = process.argv[2] ?? "//wsl.localhost/Ubuntu/var/tmp/chaos-exoplasim-wasm/source/exoplasim/plasim/src"
const strip = (text) => text.replace(/!.*$/gm, "")
const numbers = (list) => list.replace(/&/g, " ").split(",").map((value) => value.trim()).filter(Boolean).map((value) => value.replace(/d0$/i, "").replace(/d/i, "e"))

const SPECTRA = ["wavelengths", "iceblend", "iceblendmin", "iceblendmax", "seaicemin", "seaicemax", "glacalbmin", "groundblend", "oceanblend"]
const specblock = strip(await fs.readFile(path.join(sourceRoot, "specblock.f90"), "utf8"))
const spectra = Object.fromEntries(SPECTRA.map((name) => {
	const match = new RegExp(`real\\s*::\\s*${name}\\s*\\(\\s*965\\s*\\)\\s*=\\s*\\(/([\\s\\S]*?)/\\)`, "i").exec(specblock)
	if (!match) throw new Error(`${name} not found`)
	const values = numbers(match[1])
	if (values.length !== 965) throw new Error(`${name}: ${values.length} values`)
	return [name, values]
}))
await write({
	file: "src/model/climate/gcm/physics/radiation/spectrum/specblock/index.ts",
	header: "specblock.f90 (5f8dff4): 965 wavelengths (µm) and the spectral albedos\n// (%) of snow, sea ice, glacier, bare ground and ocean at each.",
	name: "SPECBLOCK",
	tables: spectra,
})

const SERIES = { obamp: 47, obrate: 47, obphas: 47, ecamp: 19, ecrate: 19, ecphas: 19, mvamp: 78, mvrate: 78, mvphas: 78 }
const radmod = strip(await fs.readFile(path.join(sourceRoot, "radmod.f90"), "utf8"))
const series = Object.fromEntries(Object.entries(SERIES).map(([name, count]) => {
	const match = new RegExp(`data\\s+${name}\\s*/([\\s\\S]*?)/`, "i").exec(radmod)
	if (!match) throw new Error(`${name} not found`)
	const values = numbers(match[1])
	if (values.length !== count) throw new Error(`${name}: ${values.length} values`)
	return [name, values]
}))
await write({
	file: "src/model/climate/gcm/calendar/berger/index.ts",
	header: "radmod.f90's orb_params (5f8dff4): Berger (1978) series for obliquity\n// (ob*), eccentricity and perihelion (ec*) and the moving vernal equinox\n// (mv*); amplitudes, rates (arcsec/yr) and phases (degrees).",
	name: "BERGER",
	tables: series,
})

async function write({ file, header, name, tables }) {
	const target = path.resolve(file)
	const body = Object.entries(tables).map(([key, values]) => `\t${key}: [\n${chunk(values).map((line) => `\t\t${line.join(", ")},`).join("\n")}\n\t],`).join("\n")
	await fs.mkdir(path.dirname(target), { recursive: true })
	await fs.writeFile(target, `// Generated by scripts/exoplasim-webgpu/fortran-tables.mjs from ExoPlaSim's\n// ${header}\nexport const ${name} = {\n${body}\n}\n`)
	console.log(`wrote ${target}`)
}

function chunk(values) {
	const lines = []
	for (let i = 0; i < values.length; i += 6) lines.push(values.slice(i, i + 6))
	return lines
}
