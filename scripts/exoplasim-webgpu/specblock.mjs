import fs from "node:fs/promises"
import path from "node:path"

// Converts the spectral tables solarini reads from ExoPlaSim's
// specblock.f90 into a TypeScript module, value for value.
// node scripts/exoplasim-webgpu/specblock.mjs <specblock.f90>
const source = process.argv[2] ?? "//wsl.localhost/Ubuntu/var/tmp/chaos-exoplasim-wasm/source/exoplasim/plasim/src/specblock.f90"
const target = path.resolve("src/model/climate/gcm/physics/radiation/spectrum/specblock/index.ts")
const TABLES = ["wavelengths", "iceblend", "iceblendmin", "iceblendmax", "seaicemin", "seaicemax", "glacalbmin", "groundblend", "oceanblend"]
const text = (await fs.readFile(source, "utf8")).replace(/!.*$/gm, "")
const tables = {}
for (const name of TABLES) {
	const match = new RegExp(`real\\s*::\\s*${name}\\s*\\(\\s*965\\s*\\)\\s*=\\s*\\(/([\\s\\S]*?)/\\)`, "i").exec(text)
	if (!match) throw new Error(`${name} not found`)
	const values = match[1].replace(/&/g, " ").split(",").map((value) => value.trim()).filter(Boolean)
	if (values.length !== 965) throw new Error(`${name}: ${values.length} values`)
	tables[name] = values
}
const body = TABLES.map((name) => `\t${name}: [\n${chunk(tables[name]).map((line) => `\t\t${line.join(", ")},`).join("\n")}\n\t],`).join("\n")
await fs.mkdir(path.dirname(target), { recursive: true })
await fs.writeFile(target, `// Generated by scripts/exoplasim-webgpu/specblock.mjs from ExoPlaSim's
// specblock.f90 (5f8dff4): 965 wavelengths (µm) and the spectral albedos
// (%) of snow, sea ice, glacier, bare ground and ocean at each.
export const SPECBLOCK = {
${body}
}
`)
console.log(`wrote ${target}`)

function chunk(values) {
	const lines = []
	for (let i = 0; i < values.length; i += 8) lines.push(values.slice(i, i + 8))
	return lines
}
